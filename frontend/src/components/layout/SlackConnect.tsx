import { useSlack } from '@/hooks/useSlack';
import { Button } from '@/components/ui/Button';

export function SlackConnect() {
  const { status, connect, disconnect } = useSlack();

  if (status.isLoading) return null;

  if (status.data?.connected) {
    return (
      <div className="flex items-center gap-2">
        <SlackIcon />
        <span className="hidden lg:inline text-xs text-secondary">
          {status.data.team} &middot; {status.data.channel}
        </span>
        <Button variant="ghost" onClick={() => disconnect.mutate()} loading={disconnect.isPending} className="text-xs px-2 py-1">
          Disconnect
        </Button>
      </div>
    );
  }

  return (
    <Button variant="secondary" onClick={() => connect.mutate()} loading={connect.isPending} className="text-xs">
      <SlackIcon />
      Connect Slack
    </Button>
  );
}

